"""The real API over the committed demo corpus, for the source view test and for trying the panel without Qdrant or a model.

    python eval/demo_server.py --port 8011

It serves backend/eval/corpus/ (four invented documents) plus a three page PDF and a workbook generated by
eval/archive_fixture.py, from an in-memory index with the hashing embedder. The four Markdown files get the repo's
ingestion identity (annotate_chunks); the PDF and the workbook go through IngestionService itself, so the panel shows a
page for one and a sheet and cells for the other. Vector store, retrieval, routes and citations are the repo's own. The ONE stand-in is the
answer text: no language model is called, so the streamed answer is a fixed sentence and the sources are what hybrid
retrieval returned for the question. The panel and its test care about the sources, not the wording.
"""
import argparse
import hashlib
import os
import sys
from pathlib import Path

os.environ.setdefault("RENDER", "true")
BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.services.chunk_identity import annotate_chunks  # noqa: E402
from eval.embedders import HashingEmbeddings  # noqa: E402
from eval.harness import CORPUS_DIR, chunk_corpus, in_memory_store, load_corpus  # noqa: E402

ANSWER = "Stand-in answer: no language model runs in the demo server. The cited passages below come from retrieval."


def annotated_corpus():
    """Corpus chunks with the identity ingestion writes: the SHA-256 of each file's bytes and the position in the file."""
    docs = load_corpus()
    chunks = chunk_corpus(docs)
    by_file = {}
    for chunk in chunks:
        by_file.setdefault(chunk.metadata["file_name"], []).append(chunk)
    for name, group in by_file.items():
        digest = hashlib.sha256((CORPUS_DIR / name).read_bytes()).hexdigest()
        # what ingestion records about a file, so the document list reads like a real upload
        details = {"file_size_kb": round((CORPUS_DIR / name).stat().st_size / 1024, 2), "upload_date": "2026-11-10T09:00:00"}
        annotate_chunks(group, digest, extra=details)
    return chunks


def ingest_generated_files():
    """A PDF and a workbook through the real ingestion service, named as a reviewer would see them."""
    import tempfile

    from app.services.ingestion import IngestionService
    from eval.archive_fixture import make_pdf, make_xlsx

    with tempfile.TemporaryDirectory() as folder:
        for name, data in (("site-report.pdf", make_pdf(4, pages=3)), ("equipment-schedule.xlsx", make_xlsx(4))):
            path = Path(folder) / name
            path.write_bytes(data)
            result = IngestionService().ingest_file(str(path))
            assert result["success"], result


def install_stand_in_answers():
    from types import SimpleNamespace

    from app.services.generation import generation_service

    generation_service.generate = lambda question, context: SimpleNamespace(answer=ANSWER, model_used="stand-in")
    generation_service.generate_stream = lambda question, context: ("stand-in", iter([ANSWER]))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--port", type=int, default=8011)
    parser.add_argument("--host", default="127.0.0.1")
    args = parser.parse_args()

    import uvicorn

    from app.main import app

    install_stand_in_answers()
    with in_memory_store(HashingEmbeddings(), annotated_corpus()):
        ingest_generated_files()
        uvicorn.run(app, host=args.host, port=args.port, log_level="warning")


if __name__ == "__main__":
    main()
